test('keeps same-day weight timestamps distinct and exports and restores a validated JSON file', async ({ page, isMobile }) => {
  await page.goto('./')
  await nav(page, 'Weight').click()
  for (const [time, weight] of [['08:00', '70'], ['21:30', '74']]) {
    await page.getByRole('button', { name: '記錄體重' }).click()
    await dialog(page).getByLabel('體重（kg）').fill(weight)
    await dialog(page).getByLabel('時間', { exact: true }).fill(time)
    await dialog(page).getByRole('button', { name: '儲存', exact: true }).click()
    await expect(dialog(page)).toHaveCount(0)
  }
  await expect(page.getByText('1/7 個測量日')).toBeVisible()
  await expect(page.locator('.stat').filter({ hasText: '最近 7 日平均' })).toContainText('72 kg')
  const rawPoints = page.locator('.recharts-line-dot[name="原始體重"]')
  await expect(rawPoints).toHaveCount(2)
  if (isMobile) await rawPoints.first().tap()
  else await rawPoints.first().click()
  await expect(page.locator('.chart-tooltip')).toContainText('08:00')
  await expect(page.locator('.chart-tooltip')).toContainText('70 kg')
  if (isMobile) await rawPoints.last().tap()
  else await rawPoints.last().click()
  await expect(page.locator('.chart-tooltip')).toContainText('21:30')
  await expect(page.locator('.chart-tooltip')).toContainText('74 kg')
  await page.getByRole('checkbox', { name: '原始體重', exact: true }).uncheck()
  await expect(rawPoints).toHaveCount(0)
  await page.getByRole('checkbox', { name: '7 日移動平均', exact: true }).uncheck()
  await expect(page.getByText('請選擇數據系列')).toBeVisible()

  await nav(page, 'More').click()
  await page.getByRole('button', { name: /備份與還原/ }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '匯出備份' }).click()
  const download = await downloadPromise
  const file = await download.path()
  expect(download.suggestedFilename()).toMatch(/^fitness-tracker-backup-.*\.json$/)
  await nav(page, 'Weight').click()
  await page.getByRole('button', { name: /刪除 .* 21:30 體重/ }).click()
  await dialog(page).getByRole('button', { name: '刪除', exact: true }).click()
  await expect(page.getByRole('button', { name: /編輯 .* 21:30 體重/ })).toHaveCount(0)

  await nav(page, 'More').click()
  await page.getByRole('button', { name: /備份與還原/ }).click()
  await page.getByLabel('選擇 JSON 檔案').setInputFiles(file)
  await expect(dialog(page).getByText('體重紀錄', { exact: true }).locator('..')).toContainText('2')
  await dialog(page).getByRole('checkbox', { name: '我確認要取代目前資料' }).check()
  await dialog(page).getByRole('button', { name: '確認還原' }).click()
  await nav(page, 'Weight').click()
  await page.reload()
  await expect(page.getByRole('button', { name: /編輯 .* 21:30 體重/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /編輯 .* 08:00 體重/ })).toBeVisible()
})

test('serves the manifest and scoped service worker on the Pages subpath, reloads offline and persists offline writes', async ({ page, context, baseURL, request }) => {
  const external: string[] = []
  page.on('request', event => { if (!event.url().startsWith(new URL(baseURL!).origin)) external.push(event.url()) })
  const response = await page.goto('./')
  expect(response?.status()).toBe(200)
  expect(new URL(page.url()).pathname).toBe(new URL(baseURL!).pathname)
  const manifestHref = await page.locator('link[rel="manifest"]').getAttribute('href')
  const manifest = await request.get(new URL(manifestHref!, baseURL!).href)
  expect(manifest.ok()).toBe(true)
  expect((await manifest.json()).start_url).toBe('./')
  for (const icon of (await manifest.json()).icons) expect((await request.get(new URL(icon.src, baseURL!).href)).ok()).toBe(true)
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller), undefined, { timeout: 15_000 })
  expect(await page.evaluate(async () => (await navigator.serviceWorker.ready).scope)).toBe(baseURL)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: '訓練紀錄', exact: true })).toBeVisible()
  await expect(page.getByText('離線', { exact: true })).toBeVisible()
  await startWorkout(page, 'Logged offline', '2026-01-05')
  await pickExercises(page, exercise)
  await enterSet(page, '10', '8')
  await saveWorkout(page)
  await page.reload()
  await expect(page.getByText('Logged offline', { exact: true })).toBeVisible()
  await nav(page, 'PR').click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '個人最佳紀錄', exact: true })).toBeVisible()
  expect(external).toEqual([])
})

test('creates, renames, archives and restores a custom assisted exercise', async ({ page }) => {
  await page.goto('./')
  await nav(page, 'More').click()
  await page.getByRole('button', { name: /動作庫/ }).click()
  await page.getByRole('button', { name: '新增自訂動作' }).click()
  await dialog(page).getByLabel('動作名稱').fill('Assisted Muscle-up')
  await dialog(page).getByLabel('主要肌群').selectOption('back')
  await dialog(page).getByLabel('器材', { exact: true }).selectOption('machine')
  await dialog(page).getByLabel('重量記錄類型').selectOption('assistance')
  await expect(dialog(page).getByRole('checkbox', { name: '計入 PR' })).toBeDisabled()
  await expect(dialog(page).getByRole('checkbox', { name: '計入 PR' })).not.toBeChecked()
  await dialog(page).getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('searchbox').fill('Muscle-up')
  await page.getByRole('button', { name: '編輯 Assisted Muscle-up', exact: true }).click()
  await dialog(page).getByLabel('動作名稱').fill('Assisted Muscle-up (Machine)')
  await dialog(page).getByRole('button', { name: '儲存', exact: true }).click()
  const renamed = 'Assisted Muscle-up (Machine)'
  await page.getByRole('button', { name: `封存 ${renamed}`, exact: true }).click()
  await dialog(page).getByRole('button', { name: '封存', exact: true }).click()
  await expect(page.getByText(renamed, { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '已封存', exact: true }).click()
  await page.getByRole('button', { name: `解除封存 ${renamed}`, exact: true }).click()
  await dialog(page).getByRole('button', { name: '解除封存', exact: true }).click()
  await page.getByRole('button', { name: '可用', exact: true }).click()
  await expect(page.getByText(renamed, { exact: true })).toBeVisible()
})

import { expect, test, type Page } from '@playwright/test'

const exercise = 'Dumbbell Bench Press'
const template = 'Upper A'
const dialog = (page: Page) => page.getByRole('dialog').last()
const nav = (page: Page, name: string) => page.getByRole('navigation', { name: '主選單' }).getByRole('link', { name: new RegExp('^' + name) })
const setWeight = (page: Page, index = 1) => page.getByRole('textbox', { name: `${exercise} 第 ${index} 組 Weight`, exact: true })
const setReps = (page: Page, index = 1) => page.getByRole('textbox', { name: `${exercise} 第 ${index} 組 Reps`, exact: true })

async function pickExercises(page: Page, ...names: string[]) {
  await page.getByRole('button', { name: '加入動作', exact: true }).click()
  for (const name of names) {
    await dialog(page).getByRole('searchbox').fill(name)
    await dialog(page).getByRole('checkbox', { name: new RegExp('^' + name) }).first().check()
  }
  await dialog(page).getByRole('button', { name: '加入動作 (' + names.length + ')' }).click()
}

async function startWorkout(page: Page, name: string, date: string, useTemplate = false) {
  await page.getByRole('button', { name: '新增 Workout', exact: true }).click()
  const form = dialog(page)
  await form.getByLabel('訓練日期').fill(date)
  if (useTemplate) await form.getByLabel('Workout Template').selectOption({ label: template })
  await form.getByLabel('Workout 名稱').fill(name)
  await form.getByRole('button', { name: '開始記錄' }).click()
  await expect(page.getByRole('heading', { name: '記錄 Workout' })).toBeVisible()
}

async function saveWorkout(page: Page) {
  await page.getByRole('button', { name: '儲存 Workout', exact: true }).click()
  await expect(page.getByRole('heading', { name: '訓練紀錄', exact: true })).toBeVisible()
}

async function addSet(page: Page) {
  const button = page.getByRole('button', { name: '新增 Set', exact: true })
  await button.evaluate(element => element.scrollIntoView({ block: 'center' }))
  await button.click()
}

async function enterSet(page: Page, weight: string, reps: string) {
  await addSet(page)
  await setWeight(page).fill(weight)
  await setReps(page).fill(reps)
}

test('creates, resumes and edits workouts, copies previous sets, applies a template, and recalculates PR after deletion', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: '建立 Template', exact: true }).click()
  await dialog(page).getByLabel('Template 名稱').fill(template)
  await pickExercises(page, exercise, 'Push-up')
  await dialog(page).getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.getByText(template, { exact: true })).toBeVisible()
  await nav(page, 'Workout').click()

  await startWorkout(page, 'Earlier', '2026-01-05', true)
  await enterSet(page, '10', '8')
  await addSet(page)
  await expect(setWeight(page, 2)).toHaveValue('10')
  await expect(setReps(page, 2)).toHaveValue('')
  await page.getByRole('button', { name: '刪除第 2 組', exact: true }).click()
  await expect(setReps(page, 2)).toHaveCount(0)
  await expect(page.getByText('草稿已儲存於此裝置')).toBeVisible()
  await page.reload()
  await expect(setReps(page)).toHaveValue('8')
  await page.getByRole('button', { name: '返回 Workout' }).click()
  await page.getByRole('button', { name: '繼續編輯' }).click()
  await expect(setWeight(page)).toHaveValue('10')
  await saveWorkout(page)

  await startWorkout(page, 'Later', '2026-01-06')
  await pickExercises(page, exercise)
  await expect(page.getByText(/上一次紀錄 · 2026-01-05/)).toBeVisible()
  await enterSet(page, '9', '4')
  await page.getByRole('button', { name: '複製上次' }).click()
  await dialog(page).getByRole('button', { name: '複製並覆蓋' }).click()
  await expect(setReps(page)).toHaveValue('8')
  await setWeight(page).fill('12.5')
  await saveWorkout(page)

  await nav(page, 'PR').click()
  await expect(page.locator('.pr-weight')).toHaveText(/12.5/)
  await nav(page, 'Workout').click()
  await page.getByText('Later', { exact: true }).click()
  await page.getByRole('button', { name: '編輯', exact: true }).click()
  await setWeight(page).fill('15')
  await saveWorkout(page)
  await nav(page, 'PR').click()
  await expect(page.locator('.pr-weight')).toHaveText(/15/)

  await nav(page, 'Workout').click()
  await page.getByRole('button', { name: '管理 Template', exact: true }).click()
  await page.getByRole('button', { name: `編輯 ${template}`, exact: true }).click()
  await dialog(page).getByLabel('Template 名稱').fill('Renamed A')
  await dialog(page).getByRole('button', { name: `下移 ${exercise}`, exact: true }).click()
  await dialog(page).getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.getByText('Renamed A', { exact: true })).toBeVisible()
  await nav(page, 'Workout').click()
  await page.getByText('Earlier', { exact: true }).click()
  const earlier = page.locator('details').filter({ has: page.getByText('Earlier', { exact: true }) })
  await expect(earlier.getByText(template, { exact: true })).toBeVisible()
  await expect(earlier.getByText(/1 個動作 · 1 Sets/)).toBeVisible()
  await expect(earlier.getByText('Push-up', { exact: true })).toHaveCount(0)

  await page.getByText('Later', { exact: true }).click()
  await page.locator('details').filter({ has: page.getByText('Later', { exact: true }) }).getByRole('button', { name: '刪除', exact: true }).click()
  await dialog(page).getByRole('button', { name: '刪除', exact: true }).click()
  await nav(page, 'PR').click()
  await expect(page.locator('.pr-weight')).toHaveText(/10/)
})

